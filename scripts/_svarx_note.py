import numpy as np

# code name -> LaTeX base symbol
BASE = {"gw": r"g^{w}", "gcpi": r"\pi", "cf10": r"\pi^{e,L}", "cf1": r"\pi^{e,S}", "magpty": r"\bar{g}^{\,\mathrm{pty}}",
        "grpe": r"g^{\mathrm{rpe}}", "grpf": r"g^{\mathrm{rpf}}", "vu": r"(V/U)", "diffcpicf": r"\mathrm{cu}",
        "shortage": r"s", "shortagema2": r"\bar{s}", "D2020Q2": r"D^{\mathrm{20Q2}}", "D2020Q3": r"D^{\mathrm{20Q3}}"}
Y = ["gw", "gcpi", "cf10", "cf1"]
# lag range of each estimated block (lo, hi), as in bb_inflation/estimation/equations.py
RANGES = {("gw", "gw"): (1, 4), ("gw", "cf1"): (1, 4), ("gw", "vu"): (1, 4), ("gw", "diffcpicf"): (1, 4), ("gw", "magpty"): (1, 1),
          ("gcpi", "gcpi"): (1, 4), ("gcpi", "gw"): (0, 4), ("gcpi", "grpe"): (0, 4), ("gcpi", "grpf"): (0, 4),
          ("gcpi", "shortagema2"): (0, 0), ("gcpi", "shortage"): (0, 1), ("gcpi", "magpty"): (0, 0),
          ("cf1", "cf1"): (1, 4), ("cf1", "cf10"): (0, 4), ("cf1", "gcpi"): (0, 4), ("cf10", "cf10"): (1, 4), ("cf10", "gcpi"): (0, 4)}
EQ_NAME = {"gw": "wage", "gcpi": "CPI", "cf10": "long-run expectations", "cf1": "short-run expectations"}


def term(var, lag=0):
    return BASE[var] + ("_{t}" if lag == 0 else "_{t-%d}" % lag)


def block_sym(eq, var):
    lo, hi = RANGES[(eq, var)]
    if lo == hi:
        return "$" + term(var, lo) + "$"
    return "$\\sum_{i=%d}^{%d} %s_{t-i}$" % (lo, hi, BASE[var])


def num(v, kind="coef"):
    if kind == "se":
        return r"\cdot" if v == 0 else "%.4f" % v
    s = "%.4f" % v
    if v == 0:
        return "0"
    if v == 1.0:                       # only the unit diagonal of A_0 is exactly 1
        return "1"
    return "0.0000" if s == "-0.0000" else s


def bmat(M, kind="coef"):
    return "\\begin{bmatrix}\n" + " \\\\\n".join(" & ".join(num(v, kind) for v in row) for row in M) + "\n\\end{bmatrix}"


def disp(body):
    return "$$\n" + body + "\n$$\n"


def vec(items):
    return "\\begin{bmatrix}\n" + " \\\\\n".join(items) + "\n\\end{bmatrix}"


